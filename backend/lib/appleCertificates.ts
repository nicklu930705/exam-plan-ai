/**
 * 取得用於 Apple SignedDataVerifier 的根憑證 Buffer 陣列
 */
export function getAppleRootCertificatesBuffers(): Buffer[] {
  const certs: Buffer[] = [];

  // 嘗試從本地 certs 目錄載入實體檔案
  try {
    const certDir = path.resolve(process.cwd(), 'certs');
    const g3Path = path.join(certDir, 'AppleRootCA-G3.cer');
    if (fs.existsSync(g3Path)) {
      certs.push(fs.readFileSync(g3Path));
    }
    const g2Path = path.join(certDir, 'AppleRootCA-G2.cer');
    if (fs.existsSync(g2Path)) {
      certs.push(fs.readFileSync(g2Path));
    }
  } catch {
    // 忽略檔案讀取失敗，使用內嵌常數
  }

  // 若檔案不存在或未讀取到，使用內嵌標準憑證
  if (certs.length === 0) {
    certs.push(Buffer.from(APPLE_ROOT_CA_G3_PEM));
    certs.push(Buffer.from(APPLE_ROOT_CA_G2_PEM));
  }

  return certs;
}
